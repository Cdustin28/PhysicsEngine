//! Writes `index.html` (by default into `target/validation/`): every scenario in [`cases`], its
//! chart, and a pass/fail table. Exits non-zero if any check fails.
//!
//! ```text
//! cargo run --release -p validation [-- OUTPUT_DIR]
//! ```

mod cases;
mod plot;

use cases::Case;
use plot::escape;
use std::fmt::Write as _;
use std::time::Instant;

fn main() {
    let out = std::env::args()
        .nth(1)
        .unwrap_or_else(|| "target/validation".into());
    let mut results = Vec::new();
    for (name, run) in cases::all() {
        let start = Instant::now();
        let case = run();
        let passed = case.checks.iter().filter(|c| c.pass).count();
        eprintln!(
            "{name:>16}: {passed}/{} passed in {:.1} s",
            case.checks.len(),
            start.elapsed().as_secs_f32()
        );
        for c in case.checks.iter().filter(|c| !c.pass) {
            eprintln!(
                "{:>18}FAIL {}: expected {}, measured {}",
                "", c.quantity, c.expected, c.measured
            );
        }
        results.push(case);
    }
    let html = page(&results);
    std::fs::create_dir_all(&out).expect("create output directory");
    let path = format!("{out}/index.html");
    std::fs::write(&path, html).expect("write page");
    let failed: usize = results
        .iter()
        .map(|c| c.checks.iter().filter(|k| !k.pass).count())
        .sum();
    eprintln!("wrote {path}");
    if failed > 0 {
        eprintln!("{failed} check(s) failed");
        std::process::exit(1);
    }
}

fn page(cases: &[Case]) -> String {
    let total: usize = cases.iter().map(|c| c.checks.len()).sum();
    let passed: usize = cases
        .iter()
        .map(|c| c.checks.iter().filter(|k| k.pass).count())
        .sum();
    let commit = std::env::var("GITHUB_SHA")
        .ok()
        .map(|s| s[..s.len().min(7)].to_string());
    let mut h = String::new();
    h.push_str(HEAD);
    let _ = write!(
        h,
        r#"<header><a class="home" href="../">PhysicsEngine</a><h1>Validation</h1>
<p class="lede">Every scenario below runs the real engine and compares it with a result from physics that's known
exactly. The page is regenerated by CI on every change, so it always reflects the current code.</p>
<p class="summary {}"><strong>{passed} of {total}</strong> checks pass.</p>
<nav>"#,
        if passed == total { "ok" } else { "bad" }
    );
    for c in cases {
        let _ = write!(h, r##"<a href="#{}">{}</a>"##, c.id, escape(c.title));
    }
    h.push_str("</nav></header><main>");
    for c in cases {
        let _ = write!(
            h,
            r#"<section id="{}"><h2>{}</h2><p class="engine">{}</p>{}"#,
            c.id,
            escape(c.title),
            escape(c.engine),
            c.explanation
        );
        if let Some(svg) = &c.chart {
            let _ = write!(h, r#"<figure>{svg}</figure>"#);
        }
        h.push_str("<table><thead><tr><th>Quantity</th><th>Expected</th><th>Measured</th><th></th></tr></thead><tbody>");
        for k in &c.checks {
            let _ = write!(
                h,
                r#"<tr><td>{}</td><td>{}</td><td>{}</td><td class="{}">{}</td></tr>"#,
                escape(&k.quantity),
                escape(&k.expected),
                escape(&k.measured),
                if k.pass { "pass" } else { "fail" },
                if k.pass { "Pass" } else { "Fail" }
            );
        }
        h.push_str("</tbody></table></section>");
    }
    h.push_str("</main><footer>Generated by <code>cargo run --release -p validation</code>");
    if let Some(sha) = commit {
        let _ = write!(
            h,
            r#" at commit <a href="https://github.com/Cdustin28/PhysicsEngine/commit/{sha}"><code>{sha}</code></a>"#
        );
    }
    h.push_str(r#". Time step 1/120 s throughout. <a href="https://github.com/Cdustin28/PhysicsEngine/tree/main/crates/validation">Source</a>.</footer></body></html>"#);
    h
}

